export function getProgressColorClass(value = 0) {
    const score = Number(value) || 0;
    if (score >= 80) return 'text-emerald-300';
    if (score >= 60) return 'text-yellow-300';
    if (score >= 40) return 'text-orange-300';
    return 'text-red-300';
}

export function calculateSubjectCompletion(subject, topics = [], userProgress = {}, testHistory = [], examType = 'SI') {
    const normalizedTopics = Array.isArray(topics) ? topics : [];
    const totalTopics = normalizedTopics.length || 1;
    const practicedTopics = normalizedTopics.filter((topic) => {
        const progress = getTopicProgress(userProgress, examType, subject, topic) || {};
        const topicAttemptCount = testHistory.filter((attempt) => attempt.exam === examType && attempt.subject === subject && attempt.topic === topic).length;
        return Number(progress.attempts || 0) > 0 || topicAttemptCount > 0;
    }).length;
    const coverage = (practicedTopics / totalTopics) * 100;
    const averageBestScore = normalizedTopics.length
        ? normalizedTopics.reduce((sum, topic) => sum + Number(getTopicProgress(userProgress, examType, subject, topic)?.bestScore || 0), 0) / normalizedTopics.length
        : 0;
    const mastery = Math.min(100, (averageBestScore / 10) * 100);
    return clamp(Math.round((coverage * 0.75) + (mastery * 0.25)), 0, 100);
}

export function getTopicStatus({ accuracy = 0, completion = 0, priority = 'LOW' }) {
    if (priority === 'COMPLETED' || completion >= 100 || accuracy >= 85) return 'Strong';
    if (priority === 'CRITICAL' || accuracy < 45 || completion < 35) return 'Critical';
    if (accuracy >= 60 && completion >= 55) return 'Needs improvement';
    if (accuracy >= 45 || completion >= 35) return 'Weak';
    return 'Not started';
}

export function calculateTopicPriority({ accuracy = 0, completion = 0, weightage = 1, attempted = 0, recentAccuracy = 0, daysRemaining = 30, revisionRequired = false }) {
    let score = 0;
    score += Math.max(0, 60 - accuracy) * 1.5;
    score += Math.max(0, 70 - completion) * 0.6;
    score += Math.max(0, weightage - 2) * 10;
    if (attempted === 0) score += 30;
    score += Math.max(0, 55 - recentAccuracy) * 1.2;
    if (daysRemaining <= 14) score += 18;
    if (revisionRequired) score += 12;

    if (score >= 95 || accuracy < 35) return 'CRITICAL';
    if (score >= 70 || weightage >= 5) return 'HIGH';
    if (score >= 40) return 'MEDIUM';
    if (completion >= 90 && accuracy >= 80) return 'COMPLETED';
    return 'LOW';
}

export function resolveTopicWeightage(examType, subject, topic, fallbackMap = {}) {
    const normalizedExam = examType === 'CONSTABLE' ? 'CONSTABLE' : 'SI';
    const weightageMap = DEFAULT_TOPIC_WEIGHTAGE[normalizedExam]?.[subject] || {};
    if (typeof weightageMap[topic] === 'number') return weightageMap[topic];
    const fallback = Number(fallbackMap[subject]?.[topic] || 1);
    return Number.isFinite(fallback) ? fallback : 1;
}

export function daysRemainingForExam(examType, today = new Date()) {
    const targetMap = {
        SI: new Date('2026-11-29T00:00:00+05:30'),
        CONSTABLE: new Date('2026-12-20T00:00:00+05:30')
    };
    const target = targetMap[examType === 'CONSTABLE' ? 'CONSTABLE' : 'SI'];
    const diff = target.getTime() - today.getTime();
    return Math.max(0, Math.ceil(diff / (1000 * 60 * 60 * 24)));
}

export function buildPlannerSnapshot(member, examType, subjectTopics = {}) {
    const normalizedExam = examType === 'CONSTABLE' ? 'CONSTABLE' : 'SI';
    const history = Array.isArray(member?.testHistory) ? member.testHistory.filter((attempt) => attempt.exam === normalizedExam) : [];
    const scopedProgress = normalizeUserProgress(member?.userProgress, member?.exam || normalizedExam, member?.testHistory, subjectTopics);
    const hasProgressData = Object.values(scopedProgress).some((progress) => {
        if (!progress || typeof progress !== 'object') return false;
        return progress.exam === normalizedExam && Number(progress.attempts || progress.total || progress.questionsAttempted || 0) > 0;
    });

    const metrics = [];
    Object.entries(subjectTopics).forEach(([subject, topics]) => {
        topics.forEach((topic) => {
            const defaultWeightage = DEFAULT_TOPIC_WEIGHTAGE[normalizedExam]?.[subject]?.[topic] ?? 1;
            const relevantAttempts = history.filter((attempt) => attempt.subject === subject && attempt.topic === topic);
            const attempted = relevantAttempts.reduce((sum, attempt) => sum + Number(attempt.total || attempt.questions?.length || 0), 0);
            const correct = relevantAttempts.reduce((sum, attempt) => sum + Number(attempt.correct || attempt.score || 0), 0);
            const incorrect = relevantAttempts.reduce((sum, attempt) => sum + Number(attempt.incorrect || 0), 0);
            const unanswered = relevantAttempts.reduce((sum, attempt) => sum + Number(attempt.unanswered || 0), 0);
            const accuracy = relevantAttempts.length
                ? Math.round(relevantAttempts.reduce((sum, attempt) => sum + Number(attempt.accuracy || 0), 0) / relevantAttempts.length)
                : 0;
            const recentAttempts = relevantAttempts.slice(0, 3);
            const recentAccuracy = recentAttempts.length
                ? Math.round(recentAttempts.reduce((sum, attempt) => sum + Number(attempt.accuracy || 0), 0) / recentAttempts.length)
                : 0;
            const currentProgress = getTopicProgress(scopedProgress, normalizedExam, subject, topic) || {};
            const completion = clamp(Math.round(((Number(currentProgress.attempts || relevantAttempts.length) * 14) + (attempted * 3) + (accuracy * 0.4)) / 1.75), 0, 100);
            const weightage = resolveTopicWeightage(normalizedExam, subject, topic, {});
            const daysRemaining = daysRemainingForExam(normalizedExam);
            const priority = calculateTopicPriority({
                accuracy,
                completion,
                weightage,
                attempted: relevantAttempts.length,
                recentAccuracy,
                daysRemaining,
                revisionRequired: accuracy < 70 || completion < 65
            });
            const status = getTopicStatus({ accuracy, completion, priority });
            const lastAttempted = relevantAttempts[0]?.date || null;
            const recommendedMinutes = clamp(Math.round(weightage * 10 + (100 - accuracy) * 0.5 + (100 - completion) * 0.4), 20, 90);

            metrics.push({
                examType: normalizedExam,
                subject,
                topic,
                attempted: relevantAttempts.length,
                correct,
                incorrect,
                unanswered,
                accuracy,
                completion,
                recentAccuracy,
                priority,
                status,
                weightage: defaultWeightage,
                lastAttempted,
                recommendedMinutes,
                revisionSessions: Math.max(0, Math.round((completion / 60) + (accuracy < 70 ? 1 : 0)))
            });
        });
    });

    const emptySummary = {
        overallProgress: 0,
        syllabusCompletion: 0,
        testsAttempted: 0,
        averageAccuracy: 0,
        strongTopics: 0,
        weakTopics: 0,
        criticalTopics: 0,
        studyStreak: 1,
        daysRemaining: daysRemainingForExam(normalizedExam),
        todaysTasks: 0,
        upcomingTasks: 0
    };

    if (!history.length && !hasProgressData) {
        return {
            examType: normalizedExam,
            generatedAt: null,
            summary: emptySummary,
            topicMetrics: metrics.sort((a, b) => {
                const priorityValue = { CRITICAL: 0, HIGH: 1, MEDIUM: 2, LOW: 3, COMPLETED: 4 };
                return priorityValue[a.priority] - priorityValue[b.priority] || b.weightage - a.weightage;
            }),
            schedule: []
        };
    }

    const totalCompletion = metrics.length ? Math.round(metrics.reduce((sum, item) => sum + item.completion, 0) / metrics.length) : 0;
    const totalTests = history.length;
    const averageAccuracy = history.length ? Math.round(history.reduce((sum, attempt) => sum + Number(attempt.accuracy || 0), 0) / history.length) : 0;
    const strongTopics = metrics.filter((metric) => metric.status === 'Strong').length;
    const weakTopics = metrics.filter((metric) => metric.status === 'Weak' || metric.status === 'Critical').length;
    const criticalTopics = metrics.filter((metric) => metric.priority === 'CRITICAL').length;
    const upcoming = [...metrics]
        .filter((metric) => metric.priority !== 'COMPLETED')
        .sort((a, b) => {
            const priorityValue = { CRITICAL: 0, HIGH: 1, MEDIUM: 2, LOW: 3, COMPLETED: 4 };
            return priorityValue[a.priority] - priorityValue[b.priority] || b.weightage - a.weightage;
        })
        .slice(0, 6)
        .map((metric, index) => {
            const startDate = new Date();
            startDate.setDate(startDate.getDate() + index + 1);
            const dateValue = startDate.toISOString().split('T')[0];
            const reason = metric.priority === 'CRITICAL'
                ? `Recent accuracy is ${metric.accuracy}% and the topic has ${metric.weightage} weightage in the exam. The planner has prioritised urgent revision.`
                : `Your recent accuracy is ${metric.recentAccuracy}% with ${metric.completion}% completion. This ${metric.subject} topic has ${metric.weightage} weightage, so it needs focused practice.`;
            return {
                id: `planner-${normalizedExam}-${metric.subject}-${metric.topic}-${dateValue}`,
                userId: member?.id || 'guest',
                examType: normalizedExam,
                date: dateValue,
                startTime: '19:00',
                endTime: '20:00',
                duration: 60,
                subject: metric.subject,
                topic: metric.topic,
                priority: metric.priority,
                reason,
                notes: `${metric.subject} • ${metric.topic}`,
                status: 'scheduled',
                autoGenerated: true,
                createdAt: new Date().toISOString(),
                updatedAt: new Date().toISOString()
            };
        });

    const summary = {
        overallProgress: totalCompletion,
        syllabusCompletion: totalCompletion,
        testsAttempted: totalTests,
        averageAccuracy,
        strongTopics,
        weakTopics,
        criticalTopics,
        studyStreak: Math.max(1, Math.min(10, Math.round(totalTests / 3 + totalCompletion / 20))),
        daysRemaining: daysRemainingForExam(normalizedExam),
        todaysTasks: upcoming.filter((task) => task.date === new Date().toISOString().split('T')[0]).length,
        upcomingTasks: upcoming.length
    };

    return {
        examType: normalizedExam,
        generatedAt: new Date().toISOString(),
        summary,
        topicMetrics: metrics.sort((a, b) => {
            const priorityValue = { CRITICAL: 0, HIGH: 1, MEDIUM: 2, LOW: 3, COMPLETED: 4 };
            return priorityValue[a.priority] - priorityValue[b.priority] || b.weightage - a.weightage;
        }),
        schedule: upcoming
    };
}

export function mergePlannerSnapshot(previousPlanner, member, examType, subjectTopics = SUBJECT_TOPICS) {
    if (!member) return previousPlanner || { examType, generatedAt: null, summary: {}, topicMetrics: [], schedule: [] };

    const nextPlanner = buildPlannerSnapshot(member, examType, subjectTopics);
    const previousSchedule = Array.isArray(previousPlanner?.schedule) ? previousPlanner.schedule : [];
    const manualTasks = previousSchedule
        .filter((task) => !task.autoGenerated)
        .map((task) => task.examType ? task : { ...task, examType: previousPlanner.examType || nextPlanner.examType });
    const otherRoleTasks = previousSchedule.filter((task) => task.autoGenerated && (task.examType || previousPlanner.examType) !== nextPlanner.examType);
    const activeRoleTasks = nextPlanner.schedule.filter((task) => task.autoGenerated && task.examType === nextPlanner.examType);
    const schedule = [...manualTasks, ...otherRoleTasks, ...activeRoleTasks]
        .sort((left, right) => left.date.localeCompare(right.date) || left.startTime.localeCompare(right.startTime));
    const activeRoleSchedule = schedule.filter((task) => (task.examType || nextPlanner.examType) === nextPlanner.examType);

    return {
        ...(previousPlanner || {}),
        ...nextPlanner,
        schedule,
        summary: {
            ...nextPlanner.summary,
            todaysTasks: activeRoleSchedule.filter((task) => task.date === new Date().toISOString().split('T')[0]).length,
            upcomingTasks: activeRoleSchedule.length
        }
    };
}
